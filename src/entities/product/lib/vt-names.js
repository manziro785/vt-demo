// Одно и то же имя у фото в карточке и на странице товара — по нему браузер
// понимает, что это «один» элемент, и анимирует перелёт (shared element).
// Имена собраны здесь, чтобы карточка и страница товара не разошлись.
export const productPhotoVt = (id) => `photo-${id}`;
export const productTitleVt = (id) => `title-${id}`;
